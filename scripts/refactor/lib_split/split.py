def apply(manifest: dict, root: Path, stages: list[str]) -> dict:
    root = Path(root)
    src_path = root / "src" / "lib.rs"
    src = src_path.read_text()
    summary = {"stages": [], "files": [], "relocs": [], "retargets": []}
    for st in stages:
        res = emit(manifest, src, stage=st)
        problems = check(res, src.encode(), manifest, stage=st, root=root)
        if problems:
            raise SplitError(f"stage {st} fails gate: {problems[:10]}")
        for f in res.files:
            p = root / f.target
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(b"".join(f.parts))
            summary["files"].append(f.target)
        _ensure_parents(root, res.files)
        for r in res.relocs:
            _apply_reloc(root, r, summary)
        for rt in manifest.get("retarget", []):
            if rt["stage"] != st:
                continue
            if rt["test_file"].startswith("src/") and \
                    any(f.target == rt["test_file"] for f in res.files):
                continue  # in-lib retarget already applied at emit
            _apply_external_retarget(root, rt, summary)
        src_path.write_bytes(res.remainder)
        src = res.remainder.decode("utf-8")
        summary["stages"].append(st)
    return summary


def _parent_module_file(root: Path, dir_path: str) -> str:
    cand = f"{dir_path}.rs"
    if (root / cand).exists():
        return cand
    if (root / dir_path / "mod.rs").exists():
        return f"{dir_path}/mod.rs"
    return cand


def _ensure_parents(root: Path, files: list[EmittedFile]) -> None:
    """Insert `mod x;` decls along every emitted file's parent chain.

    Visibility: `pub mod` when the file (or a descendant under the same
    parent) contains `pub` items — `pub use` bridges in lib.rs cannot
    re-export through a `pub(crate)` path (E0365). Dissolved test mods
    keep their original cfg attrs and `pub(crate)`.
    """
    decls: dict[str, dict] = {}
    for f in files:
        need_pub = not f.test_mod and any(it.vis == "pub" for it in f.items)
        parts = f.target.split("/")
        child = Path(f.target).stem
        attrs = f.decl_attrs if f.test_mod else []
        for i in range(len(parts) - 1, 1, -1):
            d = "/".join(parts[:i])
            if d == "src":
                break
            pfile = _parent_module_file(root, d)
            vis = "pub" if need_pub else "pub(crate)"
            cur = decls.setdefault(pfile, {}).get(child)
            if cur is None or vis == "pub":
                decls[pfile][child] = (vis, attrs)
            child = d.rsplit("/", 1)[-1]
            attrs = []
    marker = "// -- lib-split module declarations --\n"
    for pfile, children in decls.items():
        p = root / pfile
        text = p.read_text() if p.exists() else GENERATED.decode()
        if marker not in text:
            text += f"\n{marker}"
        for name, (vis, attrs) in children.items():
            m = re.search(
                rf"(?m)^(\s*)(pub(?:\([^)]*\))?\s+)?mod {re.escape(name)}\s*;",
                text)
            if m:
                if vis == "pub" and m.group(2) != "pub ":
                    # earlier stage wrote pub(crate); this file's pub
                    # items need `pub` for `pub use` — upgrade in place
                    text = (text[:m.start()] + f"{m.group(1)}pub mod {name};"
                            + text[m.end():])
                continue
            gate = "".join(a + "\n" for a in attrs)
            text += f"{gate}{vis} mod {name};\n"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


def _apply_reloc(root: Path, r: dict, summary) -> None:
    src_f = root / r["file_from"]
    dst_f = root / r["file_to"]
    if not src_f.exists():
        raise SplitError(f"reloc source missing: {r['file_from']}")
    dst_f.parent.mkdir(parents=True, exist_ok=True)
    content = src_f.read_bytes()
    cls = ri.classify(content)
    content = ri.rewrite_code(content, cls, SUPER_RX, b"crate::")
    dst_f.write_bytes(content)
    src_f.unlink()
    summary["relocs"].append(f"{r['file_from']} -> {r['file_to']}")
    parent = root / r["new_parent"]
    decl = f"#[cfg(test)]\npub(crate) mod {r['new_name']};\n"
    if parent.exists():
        text = parent.read_text()
        marker = "// -- lib-split module declarations --\n"
        if marker not in text:
            text += f"\n{marker}"
        parent.write_text(text + decl)
    else:
        parent.parent.mkdir(parents=True, exist_ok=True)
        parent.write_text(GENERATED.decode() + decl)


def _retarget_hits(text: bytes, rt: dict):
    """Locate the retarget's test fn and count `find` hits inside it.

    Returns (fn_item, hits) — fn_item is None when the fn can't be
    resolved. Shared by check() (validation gate) and apply() so a
    retarget failure is detected before any stage writes.
    """
    tname = rt["test"].rsplit("::", 1)[-1]
    items, _cls, _g = ri.parse_items(text.decode("utf-8", "replace"))

    def find_fn(pool):
        for it in pool:
            if it.name == tname and it.kind == "fn":
                return it
            sub = find_fn(it.inner)
            if sub:
                return sub
        return None

    fn = find_fn(items)
    if fn is None:
        return None, []
    seg = text[fn.start:fn.end]
    seg_cls = ri.classify(seg)
    return fn, ri.find_in_syntax(seg, seg_cls, rt["find"].encode())


def _apply_external_retarget(root: Path, rt: dict, summary) -> None:
    tf = root / rt["test_file"]
    if not tf.exists():
        raise SplitError(f"retarget: {rt['test_file']} missing")
    text = tf.read_bytes()
    fn, hits = _retarget_hits(text, rt)
    if fn is None:
        raise SplitError(f"retarget {rt['test']}: fn not found in {tf}")
    if len(hits) != 1:
        raise SplitError(f"retarget {rt['test']}: {len(hits)} find hits (want 1)")
    s, e = hits[0]
    text = text[:fn.start + s] + rt["with"].encode() + text[fn.start + e:]
    tf.write_bytes(text)
    summary["retargets"].append(f"{rt['test']} @ {rt['stage']}")


# ------------------------------------------------------------------ gate ----


def check(res: EmitResult, raw: bytes, manifest: dict,
          stage: str | None = None, root: Path | None = None) -> list[str]:
    problems: list[str] = []
    src = raw.decode("utf-8")
    items = res.items  # same objects emit() used — keys are byte offsets
    cls = ri.classify(src)
    leads, tail = ri.ownership(raw, cls, items)
    lead_of = {it.start: raw[s:e] for it, (s, e) in zip(items, leads)}
    retargets = manifest.get("retarget", [])

    def in_scope(stage_s):
        return stage is None or stage_s == stage

    relocated = set()
    for r in res.relocs:
        it = resolve_or_none(items, {"kind": "mod_decl", "name": r["decl"]})
        if it is not None:
            relocated.add(it.start)
    dissolved_mods = set()
    for e in manifest["file"]:
        modname = e.get("mod") or (e.get("slice") or {}).get("mod")
        if modname and in_scope(e["stage"]):
            it = resolve_or_none(items, {"kind": "mod_inline", "name": modname})
            if it is not None:
                dissolved_mods.add(it.start)

    # --- coverage + byte preservation --------------------------------------
    seen: dict = {}
    emitted_starts = set()
    for m in res.moved:
        it = m.item
        key = (m.parent, it.kind, it.name, it.ordinal)
        if key in seen:
            problems.append(f"duplicate move of {key}")
        seen[key] = m.target
        emitted_starts.add(it.start)
        if m.parent is None and m.lead != lead_of.get(it.start, m.lead):
            problems.append(f"gap bytes changed for {key}")
        rts = _retargets_for(retargets, m.target, it.name, stage)
        expect, _t, _d, _a = _item_transform(
            raw, it, m.target, promote=True,
            dissolving=(m.parent is not None), retargets=rts)
        if expect != m.text:
            problems.append(f"item text changed beyond sanctioned transforms: {key}")

    stay_starts = {it.start for it in res.stays}
    for it in items:
        if it.start in relocated or it.start in dissolved_mods:
            continue
        if it.start not in emitted_starts and it.start not in stay_starts:
            problems.append(f"item not covered: {(it.kind, it.name, it.ordinal)}")

    # every emitted item text must appear inside its file's joined parts
    joined: dict[str, bytes] = {}
    for f in res.files:
        joined[f.target] = b"".join(f.parts)
    for m in res.moved:
        if m.parent is not None and m.item.kind == "use":
            continue  # use seeds dedupe against the header copy
        if (m.lead + m.text) not in joined.get(m.target, b""):
            problems.append(f"{m.target}: emitted bytes missing/corrupted for {m.item.name}")

    for mod_start in dissolved_mods:
        mod = next(it for it in items if it.start == mod_start)
        inner_ids = {id(m.item) for m in res.moved if m.parent == mod.name}
        missing = [x.name for x in (mod.inner or [])
                   if x.kind != "use" and id(x) not in inner_ids]
        if missing:
            problems.append(f"{mod.name}: inner items lost {missing[:5]}")

    pos = 0
    for it in res.stays:
        seg = lead_of[it.start] + span_text(raw, it)
        idx = res.remainder.find(seg, pos)
        if idx == -1:
            problems.append(f"stay item {(it.kind, it.name)} altered in remainder")
            break
        pos = idx + len(seg)

    # --- duplicate symbols ---------------------------------------------------
    per_file: dict[str, list] = {}
    for m in res.moved:
        per_file.setdefault(m.target, []).append(m.item)
    for target, its in per_file.items():
        names: dict = {}
        for it in its:
            if it.kind == "use":
                continue
            names.setdefault((it.kind, it.name), []).append(it)
        for (k, n), group in names.items():
            if len(group) > 1 and not all(
                    any("cfg" in a.text for a in it.attrs) for it in group):
                problems.append(f"{target}: duplicate symbol {k} {n} x{len(group)}")

    # --- ordered groups ---------------------------------------------------------
    by_item = {it.start: m.target for it, m in
               ((m.item, m) for m in res.moved)}
    for it in res.stays:
        by_item[it.start] = "src/lib.rs"
    for g in manifest.get("group", []):
        tgts = set()
        for spec in g["items"]:
            it = resolve_or_none(items, spec)
            if it is not None:
                tgts.add(by_item.get(it.start))
        tgts.discard(None)
        if len(tgts) > 1:
            problems.append(f"group {g['name']} split across {sorted(tgts)}")

    # --- syntax + gaps + budget + leftover super:: -------------------------------
    for f in res.files:
        text = joined[f.target]
        try:
            _i2, _c2, gaps2 = ri.parse_items(text.decode("utf-8", "replace"))
        except ri.LexError as e:
            problems.append(f"{f.target}: emitted file fails to lex: {e}")
            continue
        if gaps2:
            problems.append(f"{f.target}: {len(gaps2)} unattributed gaps in emitted file")
        lines = text.count(b"\n") + 1
        if lines > 2000 and f.target not in SIZE_EXEMPTIONS:
            problems.append(f"{f.target}: {lines} lines exceeds 2000 budget")
        if f.test_mod:
            tcls = ri.classify(text)
            for s, e in ri.code_regions(tcls):
                if b"super::" in text[s:e]:
                    problems.append(f"{f.target}: residual super:: in emitted file")
                    break

    # --- unretargeted source scans ------------------------------------------------
    covered_scans = {
        (rt["test_file"], rt["test"].rsplit("::", 1)[-1])
        for rt in retargets if in_scope(rt["stage"])
    }
    for m in res.moved:
        tcls = ri.classify(m.text)
        for s, e in ri.code_regions(tcls):
            for im in INCLUDE_RX.finditer(m.text[s:e]):
                arg = im.group(2).decode()
                if arg == "lib.rs" or (arg.endswith("/lib.rs") and ".." not in arg):
                    if (m.target, m.item.name) not in covered_scans:
                        problems.append(
                            f"{m.target}: include arg {arg!r} resolves to "
                            f"src/lib.rs without a [[retarget]] entry")

    # --- retarget application + markers ---------------------------------------------
    applied = set(res.retargets_applied)
    for rt in retargets:
        if not in_scope(rt["stage"]):
            continue
        if not rt["test_file"].startswith("src/"):
            continue
        if rt["stage"] not in applied and any(
                f.target == rt["test_file"] for f in res.files):
            # an in-scope retarget whose find did not match is a stale entry
            if not any(m.item.name == rt["test"].rsplit("::", 1)[-1]
                       and m.target == rt["test_file"] for m in res.moved):
                problems.append(
                    f"retarget {rt['test']}@{rt['stage']}: test not emitted")

    emitted_text: dict[str, bytes] = dict(joined)
    emitted_text["src/lib.rs"] = res.remainder
    for rt in retargets:
        if not in_scope(rt["stage"]):
            continue
        for marker in rt.get("markers", []):
            mb = marker.encode()
            if stage is None:
                # end-state emit: the marker must exist SOMEWHERE — `to`
                # describes where it sits at the retarget's stage, which
                # later stages may move again.
                found = any(mb in b for b in emitted_text.values())
            else:
                found = any(mb in emitted_text.get(t, b"") for t in rt["to"])
                if not found and root is not None:
                    found = any((root / t).exists()
                                and mb in (root / t).read_bytes()
                                for t in rt["to"])
            if not found:
                problems.append(
                    f"retarget {rt['test']}: marker {marker!r} absent from {rt['to']}")

    # External retargets are validated here (not only at write time) so a
    # stage apply is all-or-nothing: a missing find aborts before files
    # or earlier retargets are written.
    if root is not None:
        for rt in retargets:
            if not in_scope(rt["stage"]):
                continue
            if rt["test_file"].startswith("src/") and any(
                    f.target == rt["test_file"] for f in res.files):
                continue  # applied at emit time on the emitted item
            tf = root / rt["test_file"]
            if not tf.exists():
                problems.append(f"retarget {rt['test']}: {rt['test_file']} missing")
                continue
            fn, hits = _retarget_hits(tf.read_bytes(), rt)
            if fn is None:
                problems.append(
                    f"retarget {rt['test']}: fn not found in {rt['test_file']}")
            elif len(hits) != 1:
                problems.append(
                    f"retarget {rt['test']}: {len(hits)} find hits (want 1)")

    # --- test inventory -------------------------------------------------------------
    before = ti.collect(src)
    after: dict = {}
    for f in res.files:
        try:
            after.update(ti.collect(
                joined[f.target].decode("utf-8", "replace"),
                module_prefix=f.module_path, file_cfgs=f.decl_attrs))
        except ri.LexError:
            pass
    after.update(ti.collect(res.remainder.decode("utf-8", "replace"),
                            module_prefix=""))
    exceptions: dict[str, list] = {}
    for rt in retargets:
        if in_scope(rt["stage"]) and rt["test_file"].startswith("src/") \
                and rt["test_file"] != "src/lib.rs":
            exceptions.setdefault(rt["test"], []).append(
                ti.Exception(stage=rt["stage"], find=rt["find"].encode(),
                             with_=rt["with"].encode()))
    d = ti.diff(before, after, exceptions=exceptions, origins=res.origins)
    for p in d.problems():
        problems.append(f"tests: {p}")

    return problems


# ------------------------------------------------------------------- main ----


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--src", type=Path, default=SRC)
    ap.add_argument("--out", type=Path, default=None,
                    help="scratch dir for emitted files (must be outside src/)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--root", type=Path, default=None)
    ap.add_argument("--stage", type=str, default=None,
                    help="apply/emit only this stage (e.g. 1a, 3b)")
    args = ap.parse_args(argv[1:])
    manifest = load_manifest(args.manifest)

    if args.apply:
        if not args.root or not args.stage:
            raise SystemExit("--apply requires --root and --stage")
        stages = args.stage.split(",")
        summary = apply(manifest, args.root, stages)
        print(f"applied {stages}: {len(summary['files'])} files, "
              f"{len(summary['relocs'])} relocs, {len(summary['retargets'])} retargets")
        return 0

    if not args.dry_run:
        raise SystemExit("use --dry-run (scratch emit) or --apply --root R --stage S")

    src = args.src.read_text()
    raw = src.encode("utf-8")
    res = emit(manifest, src, stage=args.stage)
    problems = check(res, raw, manifest, stage=args.stage)

    if args.out:
        out = args.out.resolve()
        srcdir = (REPO / "src").resolve()
        if srcdir == out or srcdir in out.parents:
            raise SystemExit("refusing to emit inside src/")
        out.mkdir(parents=True, exist_ok=True)
        for f in res.files:
            p = out / f.target
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(b"".join(f.parts))
        lib = out / "src" / "lib.rs"
        lib.parent.mkdir(parents=True, exist_ok=True)
        lib.write_bytes(res.remainder)
        print(f"emitted {len(res.files)} files into {out}")

    n_moved = len({(m.parent, m.item.kind, m.item.name, m.item.ordinal)
                   for m in res.moved})
    print(f"split {'stage ' + args.stage if args.stage else 'dry'}: "
          f"{n_moved} items -> {len(res.files)} files, {len(problems)} problems")
    for p in problems[:60]:
        print(f"  CHECK: {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
