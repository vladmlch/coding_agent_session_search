#!/usr/bin/env python3
"""Stage-aware splitter for src/lib.rs.

Modes:

  --dry-run [--stage S] [--out DIR]
      emit into memory / a scratch dir and run the preservation gate.
  --apply --root R --stage S[,S2,...]
      write the given stage(s) into the tree rooted at R. R must be a
      scratch clone/fixture unless explicitly authorized for production.

Preservation gate:

  coverage   every top-level item is emitted exactly once, stays in the
             lib.rs remainder, or is consumed by a documented transform
             (dissolved mod frame, relocated decl)
  bytes      every non-whitespace source byte is accounted: each item
             carries its leading gap (standalone comments included);
             emitted text must equal the deterministic transform of the
             original span; remainder bytes are verbatim
  cfg        same check catches cfg drift (attr bytes are inside spans)
  symbols    no un-cfg'd duplicate (kind, name) within one emitted file
  order      ordered text-marker groups stay in one file
  tests      test inventory is one-to-one by origin path with declared
             per-stage exceptions only
  scans      include args resolving to src/lib.rs must be covered by a
             [[retarget]] entry for the applied stage
  syntax     every emitted file re-parses with zero lex gaps
  budget     every emitted file is <=2000 lines unless exempted

Sanctioned transforms (each verified individually by recomputation):
  - moved non-pub items get `pub(crate)` at the head
  - moved struct/union private fields get `pub(crate)`
  - dissolved test-mod inner items get `super::` -> `crate::` at code
    positions only
  - include args relative to src/ get `../`*depth prepended
  - [[retarget]] find -> with inside the named test only
"""

