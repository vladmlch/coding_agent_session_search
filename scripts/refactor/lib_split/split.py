#!/usr/bin/env python3
"""Dry-run splitter for src/lib.rs (stage 0: never writes into src/).

Materializes the manifest's [[file]] entries into a scratch --out dir and
runs the preservation gate:

  coverage   every moved item's verbatim text appears in exactly one file
  cfg        item attribute bytes identical pre/post move
  symbols    no un-cfg'd duplicate (kind, name) within one emitted file
  order      ordered text-marker groups stay in one file, in order
  tests      test body-hash multiset preserved across the move
  syntax     rust_items re-parses every emitted file with zero gaps

Promotion: moved non-pub items get `pub(crate)` (plan: mechanical,
reversible). Items already pub/pub(crate) keep their visibility; impl,
use, macro, mod_decl and cfg(test) items are not promoted.

Include retargeting: include!/include_str! paths inside moved items are
rewritten relative to the new file's directory (they resolved against
src/ when the item lived in lib.rs).
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rust_items as ri
import test_inventory as ti

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = REPO / "src" / "lib.rs"
MANIFEST = HERE / "manifest.toml"

PROMOTABLE = {"fn", "struct", "enum", "union", "const", "static", "type", "trait", "mod_inline"}
INCLUDE_RX = re.compile(r'(include(?:_str)?!\s*\(\s*")([^"]+)(")')


class SplitError(Exception):
    pass


@dataclass
class EmittedFile:
    target: str
    stage: str
    parts: list[bytes] = field(default_factory=list)
    items: list[tuple] = field(default_factory=list)  # (item, emitted_text, parent)


def load_manifest(path: Path) -> dict:
    return tomllib.loads(path.read_text())


def anchor_of(d: dict):
    return (d["kind"], d["name"], d.get("ordinal", 0))


def resolve(items, spec):
    hits = [
        it for it in items
        if (it.kind, it.name, it.ordinal) == anchor_of(spec)
    ]
    if len(hits) != 1:
        raise SplitError(f"anchor {spec}: {len(hits)} matches")
    return hits[0]


def span_text(raw: bytes, it) -> bytes:
    return raw[it.start:it.end]


def promote(text: bytes, it) -> bytes:
    if it.kind not in PROMOTABLE or it.vis:
        return text
    if any("cfg" in a.text and "test" in a.text for a in it.attrs):
        return text
    off = it.head_start - it.start
    return text[:off] + b"pub(crate) " + text[off:]


def retarget_includes(text: bytes, target: str) -> bytes:
    """Rewrite include!/include_str! relative paths for the new file dir."""
    depth = target.count("/") - 1  # target like src/cli/x.rs -> base src/cli
    if depth < 1:
        return text

    def repl(m):
        path = m.group(2)
        if path.startswith(("../", "/")) or "CARGO_MANIFEST_DIR" in path:
            return m.group(0)
        return m.group(1) + "../" * depth + path + m.group(3)

    return INCLUDE_RX.sub(repl, text.decode("utf-8")).encode("utf-8")


def seed_header(target: str, root_uses: list[bytes]) -> bytes:
    depth = target.count("/") - 1
    lines = [b"// @generated by lib-split (stage 0 dry-run) - do not edit\n"]
    lines.append(b"use super::*;\n" if depth >= 1 else b"")
    lines.append(b"use crate::*;\n")
    for u in root_uses:
        lines.append(u if u.endswith(b"\n") else u + b"\n")
    lines.append(b"\n")
    return b"".join(lines)


def emit(manifest: dict, src: str):
    items, _cls, gaps = ri.parse_items(src)
    if gaps:
        raise SplitError(f"source has {len(gaps)} unattributed gaps")
    raw = src.encode("utf-8")

    root_uses = [span_text(raw, it) for it in items if it.kind == "use"]
    files: list[EmittedFile] = []
    moved_items = []  # (item, emitted_text, target, parent)
    dissolved = set()  # id() of split mods whose frame dissolves into slices

    for entry in manifest["file"]:
        target = entry["target"]
        stage = entry["stage"]
        if "slice" in entry:
            sl = entry["slice"]
            mod = resolve(items, {"kind": "mod_inline", "name": sl["mod"]})
            inner = mod.inner
            a = inner.index(resolve(inner, sl["first"]))
            b = inner.index(resolve(inner, sl["last"]))
            slice_items = inner[a:b + 1]
            part, parts = sl["part"], sl["parts"]
            modname = sl["mod"] if part == 1 else f"{sl['mod']}_part_{part}"
            f = EmittedFile(target=target, stage=stage)
            f.parts.append(seed_header(target, root_uses))
            attrs = b"".join(span_text(raw, a2) + b"\n" for a2 in mod.attrs)
            f.parts.append(attrs + f"mod {modname} {{\n".encode())
            use_seeds = [x for x in inner if x.kind == "use"]
            for u in use_seeds:
                txt = span_text(raw, u)
                f.parts.append(txt + b"\n")
                if part == 1:
                    f.items.append((u, txt, sl["mod"]))
            for it in slice_items:
                if it.kind == "use":
                    continue  # emitted as seed above
                txt = retarget_includes(span_text(raw, it), target)
                f.items.append((it, txt, sl["mod"]))
                f.parts.append(txt + b"\n")
            f.parts.append(b"}\n")
            files.append(f)
            dissolved.add(id(mod))
            continue

        a = items.index(resolve(items, entry["first"]))
        b = items.index(resolve(items, entry["last"]))
        span_items = items[a:b + 1]
        if stage == "stay":
            for it in span_items:
                moved_items.append((it, span_text(raw, it), "src/lib.rs", None))
            continue
        f = EmittedFile(target=target, stage=stage)
        f.parts.append(seed_header(target, root_uses))
        for it in span_items:
            txt = retarget_includes(span_text(raw, it), target)
            txt = promote(txt, it)
            f.items.append((it, txt, None))
            f.parts.append(txt + b"\n")
        files.append(f)

    for f in files:
        for it, txt, parent in f.items:
            moved_items.append((it, txt, f.target, parent))
    return files, moved_items, items, dissolved


def unpromote(txt: bytes, it) -> bytes:
    """Inverse of promote(): remove `pub(crate) ` inserted at head_start.

    Only applied to originally-private items; items that already had a
    visibility qualifier never got one inserted.
    """
    if it.vis:
        return txt
    off = it.head_start - it.start
    if txt[off:off + 11] == b"pub(crate) ":
        return txt[:off] + txt[off + 11:]
    return txt


def unretarget(txt: bytes) -> bytes:
    """Inverse of retarget_includes(): strip `../` prefixes in includes."""
    def repl(m):
        path = m.group(2)
        while path.startswith("../"):
            path = path[3:]
        return m.group(1) + path + m.group(3)
    return INCLUDE_RX.sub(repl, txt.decode("utf-8")).encode("utf-8")


def check(files, moved_items, items, raw_src: bytes, manifest, dissolved) -> list[str]:
    problems = []

    # coverage: every non-stay item moved exactly once; emitted text must
    # invert (unpromote + unretarget) back to the original bytes.
    seen = {}
    for it, txt, target, parent in moved_items:
        key = (parent, it.kind, it.name, it.ordinal)
        if target == "src/lib.rs":
            continue
        if key in seen:
            problems.append(f"duplicate move of {key}")
        seen[key] = target
        orig = raw_src[it.start:it.end]
        if unretarget(unpromote(txt, it)) != orig:
            problems.append(f"item text changed beyond promotion/includes: {key}")
    stay_in_lib = {id(it) for it, _t, tgt, _p in moved_items if tgt == "src/lib.rs"}
    for it in items:
        if id(it) in dissolved:
            continue
        key = (None, it.kind, it.name, it.ordinal)
        if key not in seen and id(it) not in stay_in_lib:
            problems.append(f"item not covered: {(it.kind, it.name, it.ordinal)}")

    # symbols: duplicate (kind,name) within one file without cfg
    per_file = {}
    for it, _txt, target, _p in moved_items:
        per_file.setdefault(target, []).append(it)
    for target, its in per_file.items():
        names = {}
        for it in its:
            names.setdefault((it.kind, it.name), []).append(it)
        for (k, n), group in names.items():
            if len(group) > 1 and k != "use":
                cfgd = all(any("cfg" in a.text for a in it.attrs) for it in group)
                if not cfgd:
                    problems.append(f"{target}: duplicate symbol {k} {n} x{len(group)}")

    # order: groups in same file
    by_item = {id(it): tgt for it, _t, tgt, _p in moved_items}
    for g in manifest.get("group", []):
        tgts = {
            by_item.get(id(resolve(items, spec)))
            for spec in g["items"]
        }
        tgts.discard(None)
        if len(tgts) > 1:
            problems.append(f"group {g['name']} split across {sorted(tgts)}")
        # order inside file preserved by construction (items emitted in order)

    # tests: body-hash multiset preserved (renames allowed, loss not).
    before = ti.collect(raw_src.decode("utf-8"))
    moved_src = b"\n".join(
        txt for _it, txt, tgt, _p in moved_items if tgt != "src/lib.rs"
    ).decode("utf-8", errors="replace")
    # parse emitted text as a synthetic module tree: wrap each file's items
    # is unnecessary — inventory walks items, and moved items are verbatim
    # (mod_inline parts renamed to *_part_N change paths; compare by hash).
    before_hashes = sorted(v["sha256"] for v in before.values())
    try:
        after = ti.collect(moved_src)
    except ri.LexError as e:
        problems.append(f"emitted source does not re-parse: {e}")
        after = {}
    after_hashes = sorted(v["sha256"] for v in after.values())
    if before_hashes != after_hashes:
        problems.append(
            f"test body multiset changed: {len(before_hashes)} before, {len(after_hashes)} after"
        )

    # syntax: each emitted file re-parses with zero gaps
    for f in files:
        text = b"".join(f.parts).decode("utf-8", errors="replace")
        try:
            _items2, _c2, gaps2 = ri.parse_items(text)
        except ri.LexError as e:
            problems.append(f"{f.target}: emitted file fails to lex: {e}")
            continue
        real_gaps = [g for g in gaps2 if g[1] - g[0] > 2]
        if real_gaps:
            problems.append(f"{f.target}: {len(real_gaps)} unattributed gaps in emitted file")
    return problems


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--src", type=Path, default=SRC)
    ap.add_argument("--out", type=Path, default=None,
                    help="scratch dir for emitted files (must be outside src/)")
    ap.add_argument("--dry-run", action="store_true", required=True)
    args = ap.parse_args(argv[1:])

    if args.out:
        out = args.out.resolve()
        srcdir = (REPO / "src").resolve()
        if srcdir == out or srcdir in out.parents:
            raise SystemExit("refusing to emit inside src/")
        out.mkdir(parents=True, exist_ok=True)

    manifest = load_manifest(args.manifest)
    src = args.src.read_text()
    raw = src.encode("utf-8")
    files, moved_items, items, dissolved = emit(manifest, src)
    problems = check(files, moved_items, items, raw, manifest, dissolved)

    if args.out:
        for f in files:
            p = args.out / f.target
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(b"".join(f.parts))
        # emit lib.rs remainder (stay items, in order)
        stay = [(it, t) for it, t, tgt, _p in moved_items if tgt == "src/lib.rs"]
        lib = args.out / "src" / "lib.rs"
        lib.parent.mkdir(parents=True, exist_ok=True)
        lib.write_bytes(b"\n".join(t for _i, t in stay))
        print(f"emitted {len(files)} files into {args.out}")

    n_moved = len({(p, it.kind, it.name, it.ordinal) for it, _t, tgt, p in moved_items if tgt != "src/lib.rs"})
    print(f"split dry-run: {n_moved} items -> {len(files)} files, {len(problems)} problems")
    for p in problems[:40]:
        print(f"  CHECK: {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
