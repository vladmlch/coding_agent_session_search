class SplitError(Exception):
    pass


@dataclass
class EmittedFile:
    target: str
    stage: str
    module_path: str
    parts: list[bytes] = field(default_factory=list)
    items: list = field(default_factory=list)
    test_mod: bool = False
    decl_attrs: list = field(default_factory=list)  # cfg attrs for `mod` decl


@dataclass
class Moved:
    item: object
    text: bytes
    orig: bytes
    lead: bytes
    target: str
    parent: str | None
    transforms: list


@dataclass
class EmitResult:
    files: list[EmittedFile]
    moved: list
    remainder: bytes
    generated: bytes
    items: list
    stays: list
    relocs: list
    retargets_applied: list
    origins: dict


def load_manifest(path: Path) -> dict:
    return tomllib.loads(path.read_text())


def anchor_of(d: dict):
    return (d["kind"], d["name"], d.get("ordinal", 0))


def resolve(items, spec):
    hits = [it for it in items if (it.kind, it.name, it.ordinal) == anchor_of(spec)]
    if len(hits) != 1:
        raise SplitError(f"anchor {spec}: {len(hits)} matches")
    return hits[0]


def resolve_or_none(items, spec):
    hits = [it for it in items if (it.kind, it.name, it.ordinal) == anchor_of(spec)]
    return hits[0] if len(hits) == 1 else None


def span_text(raw: bytes, it) -> bytes:
    return raw[it.start:it.end]


def module_path_of(target: str) -> str:
    p = target.removeprefix("src/").removesuffix(".rs")
    parts = p.split("/")
    if parts[-1] == "mod":
        parts = parts[:-1]
    return "::".join(parts)


def _assign_inner_ordinals(items) -> None:
    """Ordinals for inner items (parse_items only numbers top level)."""
    def walk(pool):
        seen: dict = {}
        for it in pool:
            key = (it.kind, it.name)
            it.ordinal = seen.get(key, 0)
            seen[key] = it.ordinal + 1
            walk(it.inner)
    walk(items)


def _promote_inserts(raw: bytes, it) -> list[int]:
    offs = []
    if it.kind in PROMOTABLE and not it.vis:
        offs.append(it.head_start - it.start)
    if it.kind in ("struct", "union"):
        txt = raw[it.start:it.end].decode("utf-8", "replace")
        offs.extend(ri.field_insert_offsets(txt, it))
    if it.kind == "impl" and " for " not in f" {it.name} ":
        # Inherent impl: private associated fns/consts/types become
        # unreachable outside the file (E0624). Trait impls ("impl T for
        # X") cannot take visibility qualifiers — leave them alone.
        txt = raw[it.start:it.end]
        cls = ri.classify(txt)
        view = ri.structure_view(txt, cls)
        bpos = view.find("{", it.head_start - it.start)
        if bpos != -1:
            body = txt[bpos + 1:-1]
            subs, _cls, _gaps = ri.parse_items(body.decode("utf-8"))
            for s in subs:
                if s.kind in ("fn", "const", "type", "static") and not s.vis:
                    offs.append(bpos + 1 + s.head_start)
    return sorted(offs)


def _apply_inserts(text: bytes, offs: list[int]) -> bytes:
    for off in reversed(offs):
        text = text[:off] + b"pub(crate) " + text[off:]
    return text


def _retarget_includes(text: bytes, target: str):
    """Rewrite include!/include_str! relative paths for the new dir.

    Returns (text, drift): drift lists include args resolving to
    src/lib.rs — those must be covered by a [[retarget]] entry.
    Rewrites happen at CODE positions only.
    """
    depth = target.count("/") - 1
    cls = ri.classify(text)
    drift = []

    def repl(m):
        path = m.group(2)
        if path.startswith(b"../") or path.startswith(b"/"):
            return m.group(0)
        resolved = posixpath.normpath("src/" + path.decode())
        if resolved == "src/lib.rs":
            drift.append(path.decode())
            return m.group(0)
        if depth < 1:
            return m.group(0)
        return m.group(1) + b"../" * depth + path + m.group(3)

    return ri.rewrite_syntax(text, cls, INCLUDE_RX, repl), drift


def _super_to_crate(text: bytes) -> bytes:
    cls = ri.classify(text)
    return ri.rewrite_code(text, cls, SUPER_RX, b"crate::")


def _apply_find(text: bytes, rt: dict) -> tuple[bytes, bool]:
    cls = ri.classify(text)
    hits = ri.find_in_syntax(text, cls, rt["find"].encode())
    if len(hits) != 1:
        return text, False
    s, e = hits[0]
    return text[:s] + rt["with"].encode() + text[e:], True


def seed_header(target: str, root_uses: list[bytes], test_mod: bool = False,
                local_names: set = frozenset(), siblings: list = ()) -> bytes:
    depth = target.count("/") - 1
    lines = [GENERATED]
    if depth >= 1 and not test_mod:
        lines.append(b"#[allow(unused_imports)]\nuse super::*;\n")
    lines.append(b"#[allow(unused_imports)]\nuse crate::*;\n")
    parent_mod = "crate::" + module_path_of(target).rsplit("::", 1)[0]
    for s in siblings:
        # slice siblings: helpers defined in one part of a dissolved mod
        # are used by the others (they shared one mod scope originally)
        lines.append(f"#[allow(unused_imports)]\nuse {parent_mod}::{s}::*;\n"
                     .encode())
    if root_uses:
        # Root uses are wrapped in a private mod and glob-imported so that
        # explicit `use` items carried in moved code shadow them by the
        # normal glob-shadowing rule instead of colliding (E0252). Paths
        # that were module-relative at crate root (`use model::X`,
        # `use self::X`) resolve differently inside a nested mod, so
        # local first segments are rewritten to `crate::…` — extern
        # crate names (not in local_names) stay untouched.
        lines.append(b"#[allow(unused_imports)]\nmod __lib_split_root_uses {\n")
        for u in root_uses:
            u = _absolutize_use(u, local_names)
            # pub(crate), not pub: the seed gives the file internal scope
            # only — `pub use` would attempt a public re-export of items
            # that are merely crate-visible (E0365).
            u2 = USE_HEAD.sub(rb"\g<ws>pub(crate) use ", u, count=1)
            lines.append(u2 if u2.endswith(b"\n") else u2 + b"\n")
        lines.append(b"}\n")
        lines.append(
            b"#[allow(unused_imports)]\nuse __lib_split_root_uses::*;\n")
    lines.append(b"\n")
    return b"".join(lines)


_USE_PATH1 = re.compile(rb'\buse\s+([A-Za-z_][A-Za-z0-9_]*|::)')


def _absolutize_use(u: bytes, local_names: set) -> bytes:
    """Make a crate-root-relative `use` path valid inside a nested mod."""
    m = _USE_PATH1.search(u)
    if not m or m.group(1) == b"::":
        return u
    first = m.group(1)
    if first == b"self":
        return u[:m.start(1)] + b"crate" + u[m.end(1):]
    if first in (b"crate", b"super"):
        return u
    if first.decode() in local_names:
        return u[:m.start(1)] + b"crate::" + u[m.start(1):]
    return u


def _item_transform(raw: bytes, it, target: str, promote: bool,
                    dissolving: bool, retargets: list):
    """The deterministic sanctioned transform for one moved item."""
    text = span_text(raw, it)
    transforms = []
    if dissolving:
        text = _super_to_crate(text)
        transforms.append("super->crate")
    text, drift = _retarget_includes(text, target)
    inserts = _promote_inserts(raw, it) if promote else []
    if inserts:
        text = _apply_inserts(text, inserts)
        transforms.append(f"promote:{len(inserts)}")
    applied = []
    for rt in retargets:
        text, ok = _apply_find(text, rt)
        if ok:
            applied.append(rt["stage"])
            transforms.append(f"retarget:{rt['stage']}")
    return text, transforms, drift, applied


def _mod_body_open(raw: bytes, cls, mod) -> int:
    view = ri.structure_view(raw, cls)
    j = view.find("{", mod.head_start, mod.end)
    if j == -1:
        raise SplitError(f"mod {mod.name}: no body brace")
    return j + 1


def _retargets_for(retargets, target: str, item_name: str, stage) -> list:
    out = [
        rt for rt in retargets
        if rt["test_file"] == target
        and rt["test"].rsplit("::", 1)[-1] == item_name
        and (stage is None or rt["stage"] == stage)
    ]
    return sorted(out, key=lambda r: STAGE_ORDER.index(r["stage"])
                  if r["stage"] in STAGE_ORDER else 99)


def emit(manifest: dict, src: str, stage: str | None = None) -> EmitResult:
    items, cls, gaps = ri.parse_items(src)
    if gaps:
        raise SplitError(f"source has {len(gaps)} unattributed gaps")
    raw = src.encode("utf-8")
    _assign_inner_ordinals(items)
    leads, tail = ri.ownership(raw, cls, items)
    lead_of = {id(it): raw[s:e] for it, (s, e) in zip(items, leads)}
    tail_bytes = raw[tail[0]:tail[1]]

    def in_scope(stage_s: str) -> bool:
        return stage is None or stage_s == stage

    retargets = manifest.get("retarget", [])
    reloc_decls = {r["decl"] for r in manifest.get("mod_reloc", [])
                   if in_scope(r["stage"])}

    # also-claimed items: skipped in their native range, emitted by owner.
    # Only in-scope owner entries claim — otherwise the item stays put.
    claimed: dict[int, str] = {}
    also_of: dict[str, list] = {}
    for e in manifest["file"]:
        if not in_scope(e["stage"]):
            continue
        for a in e.get("also", []):
            it = resolve_or_none(items, a)
            if it is None:
                continue
            claimed[id(it)] = e["target"]
            also_of.setdefault(e["target"], []).append(it)

    # Root use-seed for emitted files. Generated bridge `use` lines (added
    # by earlier apply stages) are excluded — seeding them would bloat and
    # self-import the emitted files.
    gen_cutoff = raw.find(GEN_MARKER)
    if gen_cutoff == -1:
        gen_cutoff = len(raw)
    root_uses = [
        span_text(raw, it) for it in items
        if it.kind == "use" and it.start < gen_cutoff
    ]
    local_names = {it.name for it in items}
    files: list[EmittedFile] = []
    moved: list[Moved] = []
    stays: list = []
    reloc_consumed: set[int] = set()
    dissolved_mods: set[int] = set()
    retargets_applied: list = []
    origins: dict = {}

    def emit_range(entry, a, b, target):
        f = EmittedFile(target=target, stage=entry["stage"],
                        module_path=module_path_of(target))
        f.parts.append(seed_header(target, root_uses,
                                   local_names=local_names))
        for it in items[a:b + 1]:
            if id(it) in claimed:
                continue
            rts = _retargets_for(retargets, target, it.name, stage)
            txt, transforms, drift, applied = _item_transform(
                raw, it, target, True, False, rts)
            moved.append(Moved(it, txt, span_text(raw, it), lead_of[id(it)],
                               target, None, transforms))
            retargets_applied.extend(applied)
            f.items.append(it)
            f.parts.append(lead_of[id(it)] + txt + b"\n")
        for it in also_of.get(target, []):
            rts = _retargets_for(retargets, target, it.name, stage)
            txt, transforms, drift, applied = _item_transform(
                raw, it, target, True, False, rts)
            moved.append(Moved(it, txt, span_text(raw, it), lead_of[id(it)],
                               target, None, transforms + ["also"]))
            f.items.append(it)
            f.parts.append(lead_of[id(it)] + txt + b"\n")
        files.append(f)
        origins[f.module_path] = ""
        return f

    seen_mods: set[int] = set()
    for entry in manifest["file"]:
        target = entry["target"]
        estage = entry["stage"]
        modname = entry.get("mod") or (entry.get("slice") or {}).get("mod")
        if modname:
            mod = resolve_or_none(items, {"kind": "mod_inline", "name": modname})
            if mod is None:
                if stage is not None:
                    continue  # dissolved in an earlier stage
                raise SplitError(f"anchor mod {modname}: no match")
            if not in_scope(estage):
                if id(mod) not in seen_mods:
                    stays.append(mod)
                    seen_mods.add(id(mod))
                continue
            dissolved_mods.add(id(mod))
            inner = mod.inner or []
            if "slice" in entry:
                sl = entry["slice"]
                a = inner.index(resolve(inner, sl["first"]))
                b = inner.index(resolve(inner, sl["last"]))
                slice_items = inner[a:b + 1]
                part, parts = sl["part"], sl["parts"]
            else:
                slice_items = inner
                part, parts = 1, 1
            siblings = [
                Path(e2["target"]).stem
                for e2 in manifest["file"]
                if (e2.get("mod")
                    or (e2.get("slice") or {}).get("mod")) == modname
                and e2["target"] != target
            ]
            f = EmittedFile(target=target, stage=estage,
                            module_path=module_path_of(target), test_mod=True,
                            decl_attrs=[a.text for a in mod.attrs])
            f.parts.append(seed_header(target, root_uses, test_mod=True,
                                       local_names=local_names,
                                       siblings=siblings))
            body_open = _mod_body_open(raw, cls, mod)
            inner_gap_of: dict = {}
            prev_end = None
            for x in inner:
                if prev_end is not None:
                    inner_gap_of[id(x)] = raw[prev_end:x.start]
                prev_end = x.end
            head_gap = raw[body_open:inner[0].start] if inner else b""
            tail_gap = raw[inner[-1].end:mod.end - 1] if inner else b""
            if part == 1:
                f.parts.append(lead_of[id(mod)] + head_gap)
            for x in inner:
                if x.kind != "use":
                    continue
                txt = _super_to_crate(span_text(raw, x))
                if txt.strip() == b"use crate::*;":
                    continue
                f.parts.append(txt + b"\n")
                if part == 1:
                    moved.append(Moved(x, txt, span_text(raw, x),
                                       inner_gap_of.get(id(x), b""),
                                       target, modname, ["super->crate"]))
                    f.items.append(x)
            for x in slice_items:
                if x.kind == "use":
                    continue
                rts = _retargets_for(retargets, target, x.name, stage)
                txt, transforms, drift, applied = _item_transform(
                    raw, x, target, True, True, rts)
                retargets_applied.extend(applied)
                moved.append(Moved(x, txt, span_text(raw, x),
                                   inner_gap_of.get(id(x), b""),
                                   target, modname, transforms))
                f.items.append(x)
                f.parts.append(inner_gap_of.get(id(x), b"") + txt + b"\n")
            if part == parts:
                f.parts.append(tail_gap)
            files.append(f)
            origins[f.module_path] = modname
            continue

        it_a = resolve_or_none(items, entry["first"])
        it_b = resolve_or_none(items, entry["last"])
        if it_a is None or it_b is None:
            if stage is not None:
                continue  # moved in an earlier stage
            raise SplitError(f"anchors for {target}: not found")
        a = items.index(it_a)
        b = items.index(it_b)
        span_items = items[a:b + 1]
        if estage == "stay" or not in_scope(estage):
            for it in span_items:
                if it.kind == "mod_decl" and it.name in reloc_decls:
                    reloc_consumed.add(id(it))
                    continue
                if id(it) in claimed:
                    continue  # emitted via its `also` owner
                stays.append(it)
            continue
        emit_range(entry, a, b, target)

    # mod_decl items live in lib.rs until their reloc stage consumes
    # them; they are intentionally outside every range. Items in the
    # generated bridge block are likewise lib.rs-owned stays.
    covered_ids = {id(m.item) for m in moved} | {id(s) for s in stays} \
        | reloc_consumed | dissolved_mods
    reloc_in_scope = {r["decl"] for r in manifest.get("mod_reloc", [])
                      if in_scope(r["stage"])}
    gen_start = raw.find(GEN_MARKER)
    for it in items:
        if it.kind == "mod_decl" and it.name in reloc_in_scope:
            reloc_consumed.add(id(it))
        elif it.kind == "mod_decl" and id(it) not in covered_ids:
            stays.append(it)
        elif gen_start != -1 and it.start >= gen_start and \
                id(it) not in covered_ids:
            stays.append(it)
    stays.sort(key=lambda it: it.start)

    # remainder: iterate items in order; reloc decls keep only their lead
    emitted_ids = {id(m.item) for m in moved}
    rem_parts = []
    for it in items:
        if id(it) in emitted_ids or id(it) in dissolved_mods:
            continue
        if id(it) in reloc_consumed:
            rem_parts.append(lead_of[id(it)])
        elif id(it) in {id(s) for s in stays}:
            rem_parts.append(lead_of[id(it)] + span_text(raw, it))
        # anything else is flagged by the gate as uncovered
    rem = b"".join(rem_parts) + tail_bytes
    gen, rem = _generated_block(files, stage, rem)
    rem += gen

    relocs = [r for r in manifest.get("mod_reloc", []) if in_scope(r["stage"])]
    return EmitResult(files=files, moved=moved, remainder=rem, generated=gen,
                      items=items, stays=stays, relocs=relocs,
                      retargets_applied=retargets_applied, origins=origins)


def _generated_block(files: list[EmittedFile], stage,
                     remainder: bytes = b"") -> bytes:
    if not files:
        return b""
    lines = [GEN_MARKER.decode() + "\n"]
    new_roots = sorted({
        f.target.split("/")[1] for f in files
        if f.target.count("/") >= 2
        and f.target.split("/")[1] not in EXISTING_ROOT_MODS
    })
    rem_text = remainder.decode("utf-8", "replace")
    for r in new_roots:
        need_pub = any(
            f.target.startswith(f"src/{r}/") and not f.test_mod
            and any(it.vis == "pub" for it in f.items)
            for f in files)
        m = re.search(rf"(?m)^\s*(pub(?:\([^)]*\))?\s+)?mod {re.escape(r)}\s*;",
                      rem_text)
        if m:
            if need_pub and m.group(1) != "pub ":
                # an earlier stage declared this root pub(crate); this
                # stage needs pub for `pub use` — upgrade in place
                s0, e0 = m.span()
                remainder = (remainder[:s0] + b"pub mod " + r.encode()
                             + b";" + remainder[e0:])
                rem_text = remainder.decode("utf-8", "replace")
            continue
        lines.append(f"{'pub' if need_pub else 'pub(crate)'} mod {r};\n")
    for f in files:
        if f.test_mod:
            continue
        for it in f.items:
            if it.vis == "pub" and it.kind in PROMOTABLE:
                gate = "".join(a.text + "\n" for a in it.attrs
                               if a.text.startswith("#[cfg"))
                lines.append(f"{gate}#[allow(unused_imports)]\n"
                             f"pub use crate::{f.module_path}::{{{it.name}}};\n")
    for f in files:
        gate = "".join(a + "\n" for a in f.decl_attrs
                       if a.startswith("#[cfg")) if f.test_mod else ""
        lines.append(f"{gate}#[allow(unused_imports)]\n"
                     f"pub(crate) use crate::{f.module_path}::*;\n")
    return "".join(lines).encode(), remainder


